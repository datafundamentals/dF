/**
 * Auto-generates TypeScript emulator configuration from firebase.json
 * 
 * This ensures firebase.json (Firebase CLI) and TypeScript code never drift
 * Single source of truth: packages/firebase/firebase.json
 * 
 * Usage: Run via prebuild script in package.json
 */

import { readFileSync, writeFileSync } from 'fs';
import { resolve, dirname } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// Read firebase.json from package root
const firebaseJsonPath = resolve(__dirname, '../firebase.json');
const firebaseJson = JSON.parse(readFileSync(firebaseJsonPath, 'utf-8'));

// Extract emulator ports
const emulators = firebaseJson.emulators;

if (!emulators) {
  throw new Error('firebase.json must contain emulators configuration');
}

// Build the ports object
const ports = {
  auth: emulators.auth?.port,
  firestore: emulators.firestore?.port,
  storage: emulators.storage?.port,
  functions: emulators.functions?.port,
  hosting: emulators.hosting?.port,
  ui: emulators.ui?.port,
};

// Validate all ports are defined
for (const [service, port] of Object.entries(ports)) {
  if (port === undefined) {
    throw new Error(`Missing port for ${service} in firebase.json`);
  }
}

// Generate TypeScript file
const output = `/**
 * Emulator Port Configuration
 * 
 * AUTO-GENERATED from packages/firebase/firebase.json
 * DO NOT EDIT THIS FILE MANUALLY
 * 
 * Single source of truth: packages/firebase/firebase.json
 * Generated by: packages/firebase/scripts/generate-emulator-config.mjs
 * 
 * These ports are used by Firebase emulators and must match the values
 * in firebase.json for proper emulator connectivity.
 * 
 * Standard DF monorepo ports (avoid common dev server conflicts):
 * - Auth: ${ports.auth} (standard Firebase port)
 * - Firestore: ${ports.firestore} (custom, avoids 8000/8080)
 * - Storage: ${ports.storage} (standard Firebase port)
 * - Functions: ${ports.functions} (standard Firebase port)
 * - Hosting: ${ports.hosting} (standard Firebase port)
 * - UI: ${ports.ui} (custom, avoids 4000 range used by Vite)
 */

import type { EmulatorPorts } from '@df/types/firebase.types';

export const DF_EMULATOR_PORTS: EmulatorPorts = ${JSON.stringify(ports, null, 2)} as const;

/**
 * Default host for all emulators
 * Uses 127.0.0.1 instead of localhost to avoid IPv6 issues
 */
export const DF_EMULATOR_HOST = '127.0.0.1';
`;

// Write to src/emulator-config.ts
const outputPath = resolve(__dirname, '../src/emulator-config.ts');
writeFileSync(outputPath, output, 'utf-8');

console.log('✅ Generated emulator-config.ts from firebase.json');
console.log(`   Ports: Auth=${ports.auth}, Firestore=${ports.firestore}, Storage=${ports.storage}, Functions=${ports.functions}, UI=${ports.ui}`);
